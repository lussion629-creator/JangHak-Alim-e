# 이름이 짧거나 겹치는 구는 '구' 접미사를 붙여야만 인정
AMBIG = {"중구", "동구", "서구", "남구", "북구", "강서", "고성군", "광주시"}
ORDER = list(SIDO.keys())


def _district_hits(text: str):
    hits = []
    for sido, names in SIDO.items():
        for n in names:
            if n in AMBIG:
                if n in text:
                    hits.append((sido, n))
                continue
            if re.search(n + r"(시|군|구|특례시)", text):
                hits.append((sido, n + ("구" if sido in ("서울", "부산", "대구", "인천", "광주", "대전", "울산") and n not in ("기장", "달성", "군위", "강화", "옹진", "울주") else "")))
    return hits


def infer_region(org: str, *texts: str):
    """(시도, 시군구) 추정. 전국 단위면 ("전국", "")."""
    head = org or ""
    for sido, als in SIDO_ALIASES.items():
        for a in als:
            if head.startswith(a) or a + "인재" in head or a + "장학" in head:
                d = _district_hits(head)
                return sido, (d[0][1] if d else "")
    d = _district_hits(head)
    if d:
        return d[0]
    bare = re.sub(r"^\s*(\(재\)|\(사\)|재단법인|사단법인|\(주\))\s*", "", head)
    paren = " ".join(re.findall(r"\(([^)]+)\)", head))
    for sido, names in SIDO.items():
        for n in names:
            if n in AMBIG or len(n) < 2:
                continue
            if bare.startswith(n) or n in paren:
                return sido, n
    if "광주" in head and "광주시" not in head:
        return "광주", ""
    body = " ".join(t for t in texts if t)[:600]
    for sido, als in SIDO_ALIASES.items():
        for a in als[:2]:
            if a in body:
                d = _district_hits(body)
                return sido, (d[0][1] if d and d[0][0] == sido else "")
    d = _district_hits(body)
    if d:
        return d[0]
    return "전국", ""
